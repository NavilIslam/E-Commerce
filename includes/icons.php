/**
 * Backward compatibility helper for any direct callers.
 */
function iconPaths(string $name): ?string
{
    return iconSvgElements($name);
}

/**
 * Render a Lucide vector icon.
 *
 * @param string      $name  Key from iconSvgElements()
 * @param string      $class Extra classes (icon-xs | icon-sm | icon-md | icon-lg | icon-xl | icon-2xl)
 * @param string|null $label Accessible name; null renders it decorative
 */
function icon(string $name, string $class = '', ?string $label = null): string
{
    $inner = iconSvgElements($name);
    if ($inner === null) {
        return '';
    }

    $cls  = trim('icon ' . $class);
    $a11y = $label !== null
        ? ' role="img" aria-label="' . e($label) . '"'
        : ' aria-hidden="true" focusable="false"';

    return '<svg class="' . e($cls) . '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"' . $a11y . '>'
         . $inner . '</svg>';
}

/** Map a category slug to its fallback icon. Never a generic folder. */
function categoryIcon(string $slug): string
{
    $map = [
        'electronics'           => 'cat-tech',
        'fashion-apparel'       => 'cat-fashion',
        'home-living'           => 'cat-home',
        'beauty-personal-care'  => 'cat-beauty',
        'sports-fitness'        => 'cat-sports',
        'books-stationery'      => 'cat-books',
    ];
    return $map[$slug] ?? 'store';
}

